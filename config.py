# -*- coding: utf-8 -*-

# Порт, на котором будет запущен HTTP сервер прокси
port = 1200

# Домен/хост, который будет использоваться при формировании
# ссылок, отдаваемых клиентам (в плейлистах, для сегментов и т.д.)
host_name = 'mydomain.com'

# Схема, используемая в перезаписанных ссылках (http/https), когда прокси
# доступен напрямую. За nginx (trust_x_forwarded_for = True) схема и адрес
# в ссылках берутся из запроса (X-Forwarded-Proto/Host) - см. ниже.
scheme = 'http'

# User-Agent, с которым прокси будет обращаться к провайдерам.
# Некоторые провайдеры IPTV проверяют User-Agent/Referer.
user_agent = 'Mozilla/5.0 (compatible; IPTV-Proxy/1.0)'

# Доверять заголовкам от nginx: IP клиента - из X-Forwarded-For (для
# блокировки перебора пароля /admin/), схема и адрес в ссылках плейлиста -
# из X-Forwarded-Proto и Host (клиент по http получает http-ссылки, по
# https - https, все запросы идут через nginx, а не на порт прокси).
# Ставьте True, ТОЛЬКО если прокси доступен исключительно через nginx
# (IPTV_PROXY_BIND=127.0.0.1 в .env): при прямом доступе клиент сам
# подделает заголовки. При False за nginx все клиенты видны с одного IP
# nginx (при переборе блокируется вход для всех), а ссылки ведут на
# scheme://host_name:port - напрямую на порт прокси, в обход nginx.
trust_x_forwarded_for = False

# Таймауты обращения к провайдерам, в секундах
connect_timeout = 10   # время на установку соединения
read_timeout = 30      # время ожидания данных (для живых сегментов достаточно)

# Провайдеры плейлистов: ключ -> URL плейлиста (m3u8).
#
# ВНИМАНИЕ: используется только ОДИН РАЗ, при самом первом запуске, если
# ещё не существует data/providers.json - тогда это словарь становится
# начальными данными (сидируется в providers.json и больше отсюда не
# читается). Дальнейшее управление провайдерами (добавление, изменение,
# удаление) происходит через веб-интерфейс http://<host_name>:<port>/admin/
# либо прямой правкой data/providers.json (изменения применяются после
# перезапуска процесса - как и правки этого файла).
#
# Значением может быть просто строка с URL:
#     'one': 'https://provide.one/list.m3u8',
#
# либо словарь, если нужны дополнительные заголовки именно для
# этого провайдера (например Referer или свой User-Agent):
#     'two': {
#         'url': 'https://provide.two/iptv.m3u8',
#         'headers': {
#             'Referer': 'https://provide.two/',
#             'User-Agent': 'CustomPlayer/1.0',
#         },
#     },
provider = {
    'one': 'https://provide.one/list.m3u8',
    'two': 'https://provide.two/iptv.m3u8',
}
